import os
import random
import shutil
from pathlib import Path
from PIL import Image

SOURCE_DIR = "/content/product_images"
SPLIT_DIR = "/content/product_dataset"

random.seed(42)

for label in ["authentic", "replica"]:
    files = list(Path(SOURCE_DIR, label).glob("*.jpg"))

    valid_files = []

    for file in files:
        try:
            with Image.open(file) as img:
                img.verify()
            valid_files.append(file)
        except Exception:
            pass

    random.shuffle(valid_files)

    n = len(valid_files)
    train_end = int(n * 0.70)
    val_end = train_end + int(n * 0.15)

    split_files = {
        "train": valid_files[:train_end],
        "val": valid_files[train_end:val_end],
        "test": valid_files[val_end:]
    }

    for split, paths in split_files.items():
        dest = Path(SPLIT_DIR, split, label)
        dest.mkdir(parents=True, exist_ok=True)

        for path in paths:
            shutil.copy2(path, dest / path.name)

        print(label, split, len(paths))

import tensorflow as tf

IMG_SIZE = (128, 128)
BATCH_SIZE = 32

train_ds = tf.keras.utils.image_dataset_from_directory(
    "/content/product_dataset/train",
    class_names=["authentic", "replica"],
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="binary",
    seed=42
)

val_ds = tf.keras.utils.image_dataset_from_directory(
    "/content/product_dataset/val",
    class_names=["authentic", "replica"],
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="binary",
    shuffle=False
)

test_ds = tf.keras.utils.image_dataset_from_directory(
    "/content/product_dataset/test",
    class_names=["authentic", "replica"],
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="binary",
    shuffle=False
)

print("Class mapping:", train_ds.class_names)

import tensorflow as tf
from tensorflow.keras import layers, models

model = models.Sequential([
    layers.Input(shape=(128, 128, 3)),
    layers.Rescaling(1.0 / 255),

    layers.Conv2D(32, (3, 3), activation="relu", padding="same"),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), activation="relu", padding="same"),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(128, (3, 3), activation="relu", padding="same"),
    layers.MaxPooling2D((2, 2)),

    layers.Reshape((256, 128)),
    layers.LSTM(64),

    layers.Dropout(0.3),
    layers.Dense(32, activation="relu"),
    layers.Dense(1, activation="sigmoid")
])

model.compile(
    optimizer="adam",
    loss="binary_crossentropy",
    metrics=["accuracy"]
)

model.summary()

AUTOTUNE = tf.data.AUTOTUNE

train_ds = train_ds.prefetch(AUTOTUNE)
val_ds = val_ds.prefetch(AUTOTUNE)
test_ds = test_ds.prefetch(AUTOTUNE)

early_stop = tf.keras.callbacks.EarlyStopping(
    monitor="val_loss",
    patience=3,
    restore_best_weights=True
)

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=15,
    callbacks=[early_stop]
)

import matplotlib.pyplot as plt

plt.figure(figsize=(12, 4))

plt.subplot(1, 2, 1)
